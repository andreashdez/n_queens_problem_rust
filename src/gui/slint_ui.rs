/// The browser has no threads, so its solver runs in slices on this timer.
const MIN_POLL_INTERVAL: Duration = Duration::from_millis(16);

/// Opens the native solver window and runs until it closes.
///
/// # Errors
/// Returns a Slint error if the window or its renderer cannot start.
#[cfg(not(target_arch = "wasm32"))]
pub fn run() -> Result<(), slint::PlatformError> {
    #[cfg(target_os = "linux")]
    select_linux_backend()?;
    // The app must outlive the event loop.
    let (ui, _app) = start(Storage::platform_default())?;
    ui.run()
}

/// The app ID Linux desktops use to match the window to its menu entry and
/// icon: the name of the `.desktop` file that `scripts/package-linux.sh` writes.
#[cfg(target_os = "linux")]
pub const LINUX_APP_ID: &str = "io.github.andreashdez.n-queens-solver";

/// Selects winit with the app ID set as the Wayland app ID and the X11 window class.
#[cfg(target_os = "linux")]
fn select_linux_backend() -> Result<(), slint::PlatformError> {
    use slint::winit_030::winit::platform::x11::WindowAttributesExtX11 as _;

    slint::BackendSelector::new()
        .backend_name("winit".into())
        // On Wayland, the same name becomes the app ID.
        .with_winit_window_attributes_hook(|attributes| {
            attributes.with_name(LINUX_APP_ID, LINUX_APP_ID)
        })
        .select()
}

/// Starts the solver interface in the page's `<canvas id="canvas">`.
///
/// The element with id `status_id`, if the page has one, is removed once the
/// interface starts, or shows the error if it cannot.
#[cfg(target_arch = "wasm32")]
pub fn run_web(status_id: &str) {
    let status = web_sys::window()
        .and_then(|window| window.document())
        .and_then(|document| document.get_element_by_id(status_id));
    let started = start(Storage::platform_default()).and_then(|(ui, app)| {
        ui.show()?;
        // The window and app live as long as the page.
        std::mem::forget(app);
        Ok(ui)
    });
    match (started, status) {
        (Ok(ui), status) => {
            if let Some(status) = status {
                status.remove();
            }
            // On the web this hands control to the browser's event loop.
            if let Err(error) = ui.run() {
                log::error!("the GUI's event loop stopped: {error}");
            }
            std::mem::forget(ui);
        }
        (Err(error), status) => {
            log::error!("could not start the GUI: {error}");
            if let Some(status) = status {
                // Usually a browser without WebGL.
                status.set_text_content(Some(&format!("Could not start the solver: {error}")));
            }
        }
    }
}

/// Creates the window with the stored settings and connects it to a new [`App`].
fn start(storage: Storage) -> Result<(AppWindow, Rc<RefCell<App>>), slint::PlatformError> {
    let ui = AppWindow::new()?;
    let stored = storage.load();
    let theme = stored.theme;
    let app =
        Rc::new_cyclic(|this| RefCell::new(App::new(stored, storage, ui.as_weak(), this.clone())));
    connect(&ui, &app);
    ui.invoke_use_theme(theme.index());
    refresh(&ui, &mut app.borrow_mut());
    Ok((ui, app))
}

pub(super) const fn slint_color(color: Rgba) -> slint::Color {
    slint::Color::from_argb_u8(color.a, color.r, color.g, color.b)
}

fn model<T: Clone + 'static>(items: Vec<T>) -> ModelRc<T> {
    ModelRc::new(VecModel::from(items))
}

/// Slint's `int` is an `i32`; larger settings show as its maximum.
fn slint_int(value: impl TryInto<i32>) -> i32 {
    value.try_into().unwrap_or(i32::MAX)
}

/// Settings fields are at least `min` and never negative.
fn setting(value: i32, min: u32) -> u32 {
    u32::try_from(value).unwrap_or(0).max(min)
}

/// What the Slint panels show, and everything they need besides [`AppState`].
struct App {
    state: AppState,
    theme: Theme,
    dark: bool,
    clock: web_time::Instant,
    storage: Storage,
    /// The settings as last saved, so unchanged settings are not written again.
    saved_json: String,
    ui: slint::Weak<AppWindow>,
    this: Weak<RefCell<Self>>,
    /// Polls the solver while a run is running.
    poll: Timer,
    /// Hides a notice once it expires.
    notice_timer: Timer,
    /// The board area's size in points.
    board_area: (f32, f32),
    board_viewport: Square,
    charts: charts::ChartView,
    chart_model: Rc<VecModel<ChartData>>,
    /// Whether the preset list ends with "Custom settings".
    presets_custom: Option<bool>,
    /// What run history last showed, so its list is rebuilt only when it changes.
    history_key: Option<HistoryKey>,
    #[cfg(all(not(test), not(target_arch = "wasm32")))]
    clipboard: Option<arboard::Clipboard>,
    /// What tests copied, in place of the system clipboard.
    #[cfg(test)]
    copied: Vec<String>,
}

type HistoryKey = (Vec<u64>, Option<u64>, [Option<u64>; 2], bool);

impl App {
    fn new(
        stored: StoredSettings,
        storage: Storage,
        ui: slint::Weak<AppWindow>,
        this: Weak<RefCell<Self>>,
    ) -> Self {
        let saved_json = serde_json::to_string(&stored).unwrap_or_default();
        Self {
            state: AppState::with_settings(stored.app),
            theme: stored.theme,
            dark: true,
            clock: web_time::Instant::now(),
            storage,
            saved_json,
            ui,
            this,
            poll: Timer::default(),
            notice_timer: Timer::default(),
            board_area: (0.0, 0.0),
            board_viewport: Square {
                left: 0.0,
                top: 0.0,
                side: 0.0,
            },
            charts: charts::ChartView::default(),
            chart_model: Rc::new(VecModel::default()),
            presets_custom: None,
            history_key: None,
            #[cfg(all(not(test), not(target_arch = "wasm32")))]
            clipboard: None,
            #[cfg(test)]
            copied: Vec::new(),
        }
    }

    /// Seconds since the window opened, the clock notices expire by.
    fn now(&self) -> f64 {
        self.clock.elapsed().as_secs_f64()
    }

    const fn palette(&self) -> &'static Palette {
        Palette::of(self.dark)
    }

    /// Runs `action` on this app later, from the event loop.
    fn later(
        &self,
        delay: Duration,
        timer: Option<&Timer>,
        action: impl FnOnce(&AppWindow, &mut Self) + 'static,
    ) {
        let (ui, this) = (self.ui.clone(), self.this.clone());
        // A single-shot timer calls this once, though its type allows more.
        let mut action = Some(action);
        let callback = move || {
            if let (Some(ui), Some(app), Some(action)) =
                (ui.upgrade(), this.upgrade(), action.take())
            {
                with_app(&ui, &app, action);
            }
        };
        match timer {
            Some(timer) => timer.start(TimerMode::SingleShot, delay, callback),
            None => Timer::single_shot(delay, callback),
        }
    }

    /// Starts polling the solver if a run is running.
    fn poll_while_running(&self) {
        if !self.state.is_running() || self.poll.running() {
            return;
        }
        let (ui, this) = (self.ui.clone(), self.this.clone());
        self.poll.start(
            TimerMode::Repeated,
            POLL_INTERVAL.max(MIN_POLL_INTERVAL),
            move || {
                if let (Some(ui), Some(app)) = (ui.upgrade(), this.upgrade()) {
                    with_app(&ui, &app, |ui, app| {
                        app.state.drain_worker();
                        if !app.state.is_running() {
                            app.poll.stop();
                        }
                        refresh(ui, app);
                    });
                }
            },
        );
    }

    /// Writes the settings if they changed since they were last saved.
    fn save(&mut self) {
        let stored = StoredSettings {
            app: self.state.saved_settings(),
            theme: self.theme,
        };
        let Ok(json) = serde_json::to_string(&stored) else {
            return;
        };
        if json != self.saved_json {
            self.storage.write(&json);
            self.saved_json = json;
        }
    }

    /// Copies `text` to the clipboard. Errors are returned as a notice.
    #[cfg(all(not(test), not(target_arch = "wasm32")))]
    fn copy(&mut self, text: &str) -> Result<(), String> {
        // The clipboard stays open: on X11 the copied text lives only as long as it does.
        if self.clipboard.is_none() {
            self.clipboard = Some(arboard::Clipboard::new().map_err(|error| error.to_string())?);
        }
        self.clipboard
            .as_mut()
            .expect("opened above")
            .set_text(text)
            .map_err(|error| error.to_string())
    }

    /// Tests keep what they copy instead of replacing the system clipboard.
    #[cfg(test)]
    #[allow(
        clippy::unnecessary_wraps,
        reason = "Matches the real copy, which can fail."
    )]
    fn copy(&mut self, text: &str) -> Result<(), String> {
        self.copied.push(text.to_owned());
        Ok(())
    }

    /// Copies `text` to the clipboard. Errors are returned as a notice.
    #[cfg(all(not(test), target_arch = "wasm32"))]
    #[allow(
        clippy::unused_self,
        clippy::needless_pass_by_ref_mut,
        clippy::unnecessary_wraps,
        reason = "Matches the native copy, which keeps the clipboard open and can fail."
    )]
    fn copy(&mut self, text: &str) -> Result<(), String> {
        let clipboard = web_sys::window()
            .ok_or("no browser window")?
            .navigator()
            .clipboard();
        // The browser finishes the copy asynchronously.
        let _ = clipboard.write_text(text);
        Ok(())
    }
}

/// Runs `action` on the app, or right after the current action if one is
/// running: Slint can call back into the app while the app is updating it.
fn with_app(
    ui: &AppWindow,
    app: &Rc<RefCell<App>>,
    action: impl FnOnce(&AppWindow, &mut App) + 'static,
) {
    if let Ok(mut borrowed) = app.try_borrow_mut() {
        action(ui, &mut borrowed);
    } else {
        let (ui, app) = (ui.as_weak(), Rc::clone(app));
        Timer::single_shot(Duration::ZERO, move || {
            if let Some(ui) = ui.upgrade() {
                with_app(&ui, &app, action);
            }
        });
    }
}

/// Connects a callback of a Slint global to an action on the app.
macro_rules! on {
    ($ui:expr, $app:expr, $global:ident.$callback:ident, |$u:ident, $a:ident $(, $arg:ident)*| $body:expr) => {{
        let (weak, app) = ($ui.as_weak(), Rc::clone($app));
        $ui.global::<$global>().$callback(move |$($arg),*| {
            if let Some(ui) = weak.upgrade() {
                with_app(&ui, &app, move |$u, $a| $body);
            }
        });
    }};
}

fn connect(ui: &AppWindow, app: &Rc<RefCell<App>>) {
    {
        let (weak, app) = (ui.as_weak(), Rc::clone(app));
        ui.on_theme_changed(move || {
            if let Some(ui) = weak.upgrade() {
                with_app(&ui, &app, |ui, app| {
                    app.dark = ui.get_dark();
                    show_colors(ui, app.palette());
                    refresh(ui, app);
                });
            }
        });
    }
    connect_top_bar(ui, app);
    connect_controls(ui, app);
    connect_board(ui, app);
    connect_charts(ui, app);
    connect_history(ui, app);
}

fn connect_top_bar(ui: &AppWindow, app: &Rc<RefCell<App>>) {
    on!(ui, app, TopBarState.on_run, |ui, app| {
        app.state.start_run();
        app.poll_while_running();
        refresh(ui, app);
    });
    on!(ui, app, TopBarState.on_cancel, |ui, app| {
        app.state.cancel_run();
        show_top_bar(ui, app);
    });
    on!(ui, app, TopBarState.on_toggle_history, |ui, app| {
        app.state.show_history = !app.state.show_history;
        refresh(ui, app);
    });
    on!(ui, app, TopBarState.on_choose_theme, |ui, app, index| {
        app.theme = Theme::from_index(index);
        app.save();
        show_top_bar(ui, app);
        // Switching the theme calls back into the app, so it waits for this action to end.
        let ui = ui.as_weak();
        Timer::single_shot(Duration::ZERO, move || {
            if let Some(ui) = ui.upgrade() {
                ui.invoke_use_theme(index);
            }
        });
    });
}

fn connect_controls(ui: &AppWindow, app: &Rc<RefCell<App>>) {
    on!(ui, app, ControlsState.on_choose_preset, |ui, app, index| {
        if let Some(&preset) = usize::try_from(index)
            .ok()
            .and_then(|index| GuiPreset::ALL.get(index))
        {
            app.state.choose_preset(preset);
        }
        refresh(ui, app);
    });
    on!(ui, app, ControlsState.on_settings_edited, |ui, app| {
        read_settings(ui, &mut app.state);
        refresh(ui, app);
    });
    on!(ui, app, ControlsState.on_seed_edited, |ui, app| {
        let controls = ui.global::<ControlsState>();
        app.state.seed_text = controls.get_seed_text().into();
        app.state.seed_text_edited();
        if controls.get_seed_text() != app.state.seed_text.as_str() {
            controls.set_seed_text(app.state.seed_text.as_str().into());
        }
        refresh(ui, app);
    });
    on!(ui, app, ControlsState.on_seed_focus_changed, |ui, app| {
        show_controls(ui, app);
    });
    on!(ui, app, ControlsState.on_randomize_seed, |ui, app| {
        app.state.randomize_seed();
        refresh(ui, app);
    });
}

/// Takes every run setting from the controls.
fn read_settings(ui: &AppWindow, state: &mut AppState) {
    if state.is_running() {
        return;
    }
    let controls = ui.global::<ControlsState>();
    let config = &mut state.config;
    config.solver = if controls.get_solver() == 1 {
        Solver::MinConflicts
    } else {
        Solver::Ga
    };
    config.board_size = u16::try_from(setting(controls.get_board_size(), 1)).unwrap_or(u16::MAX);
    config.population_size = setting(controls.get_population_size(), 1);
    config.max_epochs = setting(controls.get_max_epochs(), 1);
    config.mutation_rate = controls.get_mutation_rate();
    config.elite_ratio = controls.get_elite_ratio();
    config.offspring_ratio = controls.get_offspring_ratio();
    config.min_diversity_ratio = controls.get_min_diversity_ratio();
    config.selection_strategy = if controls.get_selection() == 1 {
        SelectionStrategy::Tournament
    } else {
        SelectionStrategy::Roulette
    };
    config.tournament_size = setting(controls.get_tournament_size(), 1);
    config.local_search_rate = controls.get_local_search_rate();
    config.local_search_attempts = setting(controls.get_local_search_attempts(), 0);
    config.allow_unsolvable = controls.get_allow_unsolvable();
    config.normalize();
}

fn connect_board(ui: &AppWindow, app: &Rc<RefCell<App>>) {
    on!(
        ui,
        app,
        BoardState.on_area_resized,
        |ui, app, width, height| {
            if app.board_area != (width, height) {
                app.board_area = (width, height);
                show_board(ui, app);
            }
        }
    );
    on!(ui, app, BoardState.on_hover, |ui, app, x, y| {
        show_board_hover(ui, app, Point::new(x, y));
    });
    on!(ui, app, BoardState.on_drag, |ui, app, dx, dy| {
        let side = app.board_viewport.side.max(1.0);
        app.state
            .board_view
            .move_by(Point::new(dx / side, dy / side));
        show_board(ui, app);
    });
    on!(ui, app, BoardState.on_click, |ui, app, x, y| {
        let clicked = queen_under(app, Point::new(x, y));
        app.state.selected_queen = if clicked == app.state.selected_queen {
            None
        } else {
            clicked
        };
        show_board(ui, app);
    });
    on!(ui, app, BoardState.on_zoom_at, |ui, app, factor, x, y| {
        let viewport = app.board_viewport;
        if viewport.side > 0.0 {
            let anchor = Point::new(
                (x - viewport.left) / viewport.side,
                (y - viewport.top) / viewport.side,
            );
            let view = &mut app.state.board_view;
            view.set_zoom(view.zoom() * factor, anchor);
            show_board(ui, app);
        }
    });
    on!(ui, app, BoardState.on_zoom_in, |ui, app| {
        app.state.board_view.zoom_in();
        show_board(ui, app);
    });
    on!(ui, app, BoardState.on_zoom_out, |ui, app| {
        app.state.board_view.zoom_out();
        show_board(ui, app);
    });
    on!(ui, app, BoardState.on_fit, |ui, app| {
        app.state.board_view = super::board::BoardView::default();
        show_board(ui, app);
    });
    on!(ui, app, BoardState.on_clear_selection, |ui, app| {
        app.state.selected_queen = None;
        show_board(ui, app);
    });
}

fn connect_charts(ui: &AppWindow, app: &Rc<RefCell<App>>) {
    on!(ui, app, ChartsState.on_show_view, |ui, app, view| {
        app.state.chart_view = if view == 1 {
            ChartView::Comparison
        } else {
            ChartView::Metrics
        };
        show_charts(ui, app);
    });
    on!(ui, app, ChartsState.on_log_scale_toggled, |ui, app| {
        app.state.log_conflicts = ui.global::<ChartsState>().get_log_scale();
        refresh(ui, app);
    });
    on!(
        ui,
        app,
        ChartsState.on_plot_resized,
        |ui, app, width, height| {
            if app.charts.plot != (width, height) {
                app.charts.plot = (width, height);
                show_charts(ui, app);
            }
        }
    );
    on!(ui, app, ChartsState.on_pan, |ui, app, fraction| {
        app.charts.pan(f64::from(fraction));
        show_charts(ui, app);
    });
    on!(ui, app, ChartsState.on_zoom, |ui, app, factor, anchor| {
        app.charts.zoom(f64::from(factor), f64::from(anchor));
        show_charts(ui, app);
    });
    on!(ui, app, ChartsState.on_hover, |ui, app, fraction| {
        app.charts
            .hover((fraction >= 0.0).then_some(f64::from(fraction)));
        show_charts(ui, app);
    });
    on!(ui, app, ChartsState.on_reset, |ui, app| {
        app.charts.reset();
        show_charts(ui, app);
    });
    on!(ui, app, ChartsState.on_toggle, |ui, app, index, label| {
        app.charts
            .toggle(usize::try_from(index).unwrap_or(usize::MAX), &label);
        show_charts(ui, app);
    });
}

fn connect_history(ui: &AppWindow, app: &Rc<RefCell<App>>) {
    let id = |id: i32| u64::try_from(id).unwrap_or(u64::MAX);
    on!(ui, app, HistoryState.on_view, |ui, app, run| {
        app.state.view_saved_run(id(run));
        refresh(ui, app);
    });
    on!(ui, app, HistoryState.on_view_current, |ui, app| {
        app.state.view_current_run();
        refresh(ui, app);
    });
    on!(ui, app, HistoryState.on_mark, |ui, app, slot, run| {
        app.state.toggle_comparison(usize::from(slot == 1), id(run));
        refresh(ui, app);
    });
    on!(ui, app, HistoryState.on_rerun, |ui, app, run| {
        app.state.rerun_saved(id(run));
        app.poll_while_running();
        refresh(ui, app);
    });
    on!(ui, app, HistoryState.on_copy_command, |ui, app, run| {
        let run = id(run);
        if let Some(command) = app.state.cli_command(run) {
            let now = app.now();
            match app.copy(&command) {
                Ok(()) => app.state.command_copied(run, now),
                Err(error) => {
                    app.state
                        .notify(format!("Could not copy the command: {error}"), true, now);
                }
            }
        }
        show_top_bar(ui, app);
    });
    on!(ui, app, HistoryState.on_export, |ui, app, run| {
        let now = app.now();
        app.state.export_run(id(run), now);
        show_top_bar(ui, app);
    });
}

/// Shows the whole app state.
fn refresh(ui: &AppWindow, app: &mut App) {
    show_top_bar(ui, app);
    show_controls(ui, app);
    show_board(ui, app);
    show_charts(ui, app);
    show_history(ui, app);
    app.save();
}

fn show_colors(ui: &AppWindow, palette: &Palette) {
    let colors = ui.global::<AppColors>();
    colors.set_success(slint_color(palette.success));
    colors.set_warning(slint_color(palette.warning));
    colors.set_error_text(slint_color(palette.error_text));
    colors.set_accent(slint_color(palette.accent));
    colors.set_empty_board(slint_color(palette.empty_board));
    colors.set_empty_board_text(slint_color(palette.empty_board_text));
    colors.set_selected_queen(slint_color(palette.selected_queen));
    colors.set_coordinate(slint_color(palette.coordinate));
    colors.set_queen_label(slint_color(palette.queen_label));
}

fn show_top_bar(ui: &AppWindow, app: &mut App) {
    let top_bar = ui.global::<TopBarState>();
    let state = &app.state;
    top_bar.set_running(state.is_running());
    top_bar.set_cancel_requested(state.cancel_requested);
    if let Some((fraction, text, step)) = state.run_progress() {
        top_bar.set_progress(fraction);
        top_bar.set_progress_text(text.into());
        top_bar.set_step_name(step.one.into());
    }
    let (status, tone) = state.status();
    top_bar.set_status(status.into());
    top_bar.set_status_toned(tone.is_some());
    if let Some(tone) = tone {
        top_bar.set_status_color(slint_color(app.palette().tone(tone)));
    }
    top_bar.set_history_count(slint_int(state.archive.len()));
    top_bar.set_show_history(state.show_history);
    top_bar.set_theme(app.theme.index());

    let now = app.now();
    let notice = app
        .state
        .current_notice(now)
        .map(|notice| (notice.text.clone(), notice.is_error, notice.expires_at));
    let (text, is_error) = notice
        .as_ref()
        .map_or((String::new(), false), |(text, is_error, _)| {
            (text.clone(), *is_error)
        });
    top_bar.set_notice(text.into());
    top_bar.set_notice_is_error(is_error);
    if let Some((_, _, expires_at)) = notice {
        let delay = Duration::from_secs_f64((expires_at - now).max(0.0) + 0.05);
        app.later(delay, Some(&app.notice_timer), show_top_bar);
    }
}

fn show_controls(ui: &AppWindow, app: &mut App) {
    let controls = ui.global::<ControlsState>();
    let state = &mut app.state;
    controls.set_running(state.is_running());

    let preset = GuiPreset::matching(&state.config);
    if app.presets_custom != Some(preset.is_none()) {
        app.presets_custom = Some(preset.is_none());
        let mut labels: Vec<SharedString> = GuiPreset::ALL
            .iter()
            .map(|preset| preset.label().into())
            .collect();
        if preset.is_none() {
            labels.push("Custom settings".into());
        }
        controls.set_presets(model(labels));
    }
    let preset_index = preset.map_or(GuiPreset::ALL.len(), |preset| {
        GuiPreset::ALL
            .iter()
            .position(|&choice| choice == preset)
            .unwrap_or_default()
    });
    controls.set_preset_index(slint_int(preset_index));

    // Follow seeds set elsewhere (presets, reruns, saved settings) unless mid-edit.
    if !controls.get_seed_has_focus() {
        state.sync_seed_text();
    }
    if controls.get_seed_text() != state.seed_text.as_str() {
        controls.set_seed_text(state.seed_text.as_str().into());
    }
    let seed_valid = state.seed_text_is_valid();
    controls.set_seed_valid(seed_valid);
    controls.set_seed_help(
        if seed_valid {
            SEED_HELP
        } else {
            INVALID_SEED_HELP
        }
        .into(),
    );
    controls.set_budget_summary(state.budget_summary().into());

    let config = &state.config;
    controls.set_solver(i32::from(config.solver == Solver::MinConflicts));
    controls.set_board_size(i32::from(config.board_size));
    controls.set_population_size(slint_int(config.population_size));
    controls.set_max_epochs(slint_int(config.max_epochs));
    controls.set_mutation_rate(config.mutation_rate);
    controls.set_elite_ratio(config.elite_ratio);
    controls.set_offspring_ratio(config.offspring_ratio);
    controls.set_min_diversity_ratio(config.min_diversity_ratio);
    controls.set_selection(i32::from(
        config.selection_strategy == SelectionStrategy::Tournament,
    ));
    controls.set_tournament_size(slint_int(config.tournament_size));
    controls.set_local_search_rate(config.local_search_rate);
    controls.set_local_search_attempts(slint_int(config.local_search_attempts));
    controls.set_allow_unsolvable(config.allow_unsolvable);

    let panel = state.metrics_panel();
    controls.set_metrics_title(panel.title.into());
    controls.set_has_metrics(panel.rows.is_some());
    let rows = panel
        .rows
        .unwrap_or_default()
        .into_iter()
        .map(|(label, value)| MetricRow {
            label: label.into(),
            value: value.into(),
        });
    controls.set_metrics(model(rows.collect()));
    controls.set_metrics_footer(model(
        panel.footer.into_iter().map(SharedString::from).collect(),
    ));
}

/// The queen under `pointer`, in board-area coordinates.
fn queen_under(app: &App, pointer: Point) -> Option<usize> {
    let viewport = app.board_viewport;
    let inside = (viewport.left..viewport.right()).contains(&pointer.x)
        && (viewport.top..viewport.bottom()).contains(&pointer.y);
    let (positions, _, _) = app.state.current_board()?;
    inside
        .then(|| queen_at_pointer(app.state.board_view.board(viewport), positions, pointer))
        .flatten()
}

fn show_board_hover(ui: &AppWindow, app: &App, pointer: Point) {
    let board = ui.global::<BoardState>();
    let hovered = queen_under(app, pointer);
    let text = hovered
        .zip(app.state.current_board())
        .map(|(column, (positions, conflicts, _))| hover_text(positions, conflicts, column))
        .unwrap_or_default();
    board.set_hovering_queen(hovered.is_some());
    board.set_hover_text(text.into());
}

fn show_board(ui: &AppWindow, app: &mut App) {
    let board = ui.global::<BoardState>();
    let size = app
        .state
        .current_board()
        .map(|(positions, _, _)| positions.len());
    if app
        .state
        .selected_queen
        .is_some_and(|column| Some(column) >= size)
    {
        app.state.selected_queen = None;
    }
    let (width, height) = app.board_area;
    let viewport = board::viewport(size, width, height);
    app.board_viewport = viewport;
    board.set_viewport_x(viewport.left);
    board.set_viewport_y(viewport.top);
    board.set_viewport_side(viewport.side);
    board.set_empty_text(EMPTY_BOARD_TEXT.into());
    board.set_selection_height(SELECTION_INFO_HEIGHT);
    let help: Vec<SharedString> = HELP_TEXT
        .iter()
        .enumerate()
        .flat_map(|(index, group)| {
            (index > 0)
                .then_some("")
                .into_iter()
                .chain(group.iter().copied())
        })
        .map(SharedString::from)
        .collect();
    if board.get_help().row_count() != help.len() {
        board.set_help(model(help));
    }

    let state = &app.state;
    let view = state.board_view;
    board.set_zoom_label(view.zoom_label().into());
    board.set_can_zoom_in(view.can_zoom_in());
    board.set_can_zoom_out(view.can_zoom_out());
    let Some((positions, conflicts, conflicts_sum)) = state
        .current_board()
        .filter(|_| width > 0.0 && height > 0.0)
    else {
        board.set_has_board(false);
        board.set_has_selection(false);
        board.set_coordinates(model(Vec::new()));
        board.set_queen_labels(model(Vec::new()));
        board.set_hover_text(SharedString::new());
        return;
    };
    let scene = board::Scene {
        positions,
        conflicts,
        selected: state.selected_queen,
        view,
        palette: app.palette(),
    };
    board.set_has_board(true);
    board.set_summary(board_summary(positions.len(), conflicts_sum).into());
    let scale = ui.window().scale_factor();
    board.set_image(slint::Image::from_rgba8_premultiplied(board::render(
        &scene,
        viewport.side,
        scale,
    )));
    board.set_queen_labels(model(board::queen_labels(&scene, viewport)));
    board.set_coordinates(model(board::coordinate_labels(&scene, viewport)));
    board.set_has_selection(state.selected_queen.is_some());
    if let Some(column) = state.selected_queen {
        let (title, details) =
            selection_text(positions, column, &attacking_columns(positions, column));
        board.set_selection_title(title.into());
        board.set_selection_details(details.into());
    }
}

fn show_charts(ui: &AppWindow, app: &mut App) {
    let charts = ui.global::<ChartsState>();
    let state = &app.state;
    let palette = Palette::of(app.dark);
    charts.set_view(i32::from(state.chart_view == ChartView::Comparison));
    charts.set_log_scale(state.log_conflicts);
    let (message, note, caption, specs, key) = match state.chart_view {
        ChartView::Metrics => {
            let key = (0, state.archive.viewed, state.chart_generation);
            match metric_charts(state.chart_history(), palette, state.log_conflicts) {
                None => (
                    NO_METRICS_TEXT,
                    String::new(),
                    String::new(),
                    Vec::new(),
                    key,
                ),
                Some(charts) => (
                    "",
                    charts.note.unwrap_or_default(),
                    String::new(),
                    charts.charts,
                    key,
                ),
            }
        }
        ChartView::Comparison => match state.archive.comparison_pair() {
            None => (
                NO_COMPARISON_TEXT,
                String::new(),
                String::new(),
                Vec::new(),
                (1, None, 0),
            ),
            Some([a, b]) => {
                let comparison = comparison(a, b, palette, state.log_conflicts);
                (
                    "",
                    comparison.context,
                    comparison.caption,
                    vec![comparison.chart],
                    (1, Some(a.id), b.id),
                )
            }
        },
    };
    charts.set_message(message.into());
    charts.set_note(note.into());
    charts.set_caption(caption.into());
    let data = app.charts.show(key, &specs);
    // Updating rows in place keeps a drag on a chart going while a run adds samples.
    let rows = &app.chart_model;
    if rows.row_count() == data.len() {
        for (index, chart) in data.into_iter().enumerate() {
            rows.set_row_data(index, chart);
        }
    } else {
        rows.set_vec(data);
    }
    if charts.get_charts().row_count() != rows.row_count() || charts.get_charts().row_count() == 0 {
        charts.set_charts(ModelRc::from(Rc::clone(&app.chart_model)));
    }
}

fn show_history(ui: &AppWindow, app: &mut App) {
    let history = ui.global::<HistoryState>();
    let state = &app.state;
    history.set_caption(HISTORY_CAPTION.into());
    history.set_empty_text(EMPTY_HISTORY_TEXT.into());
    history.set_running(state.is_running());
    history.set_viewing_saved(state.archive.viewed.is_some());
    history.set_has_runs(!state.archive.is_empty());
    let key: HistoryKey = (
        state.archive.newest_first().map(|run| run.id).collect(),
        state.archive.viewed,
        state.archive.compare,
        state.is_running(),
    );
    if app.history_key.as_ref() == Some(&key) {
        return;
    }
    let runs = state
        .archive
        .newest_first()
        .map(|run| SavedRunItem {
            id: slint_int(run.id),
            title: run.title().into(),
            stop_reason: run.result.stop_reason.to_string().into(),
            summary: run.summary().into(),
            settings: model(
                settings_lines(&run.result.config)
                    .into_iter()
                    .map(SharedString::from)
                    .collect(),
            ),
            viewed: state.archive.viewed == Some(run.id),
            marked_a: state.archive.compare[0] == Some(run.id),
            marked_b: state.archive.compare[1] == Some(run.id),
        })
        .collect();
    history.set_runs(model(runs));
    app.history_key = Some(key);
}

